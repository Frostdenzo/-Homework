n1 = int(input("введіть число: "))
n2 = int(input("введіть число: "))
n3 = int(input("введіть число: "))

action = input("Виберіть дію: 1 - Сума, 2 - Добуток: ")
if action == '1':
   print(f"сумма чисел дорьвнює: {n1 + n2 + n3}")
elif action == '2':
    print(f"добуток чисел дорівнює: {n1 * n2 * n3}")
else:
    print("помилка виберіть 1 або 2")
